create or replace function public.guild_intelligence_capture_status(p_status text)
returns text
language sql
immutable
as $$
  select case p_status
    when 'active' then 'captured'
    when 'partial' then 'partial'
    when 'pending_source' then 'source_pending'
    when 'legacy_reference' then 'not_applicable'
    else 'failed'
  end
$$;

create or replace function public.guild_intelligence_page_payload(
  p_guild_id uuid,
  p_page_key text,
  p_report_date date,
  p_timezone text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_start timestamptz := (p_report_date::timestamp at time zone p_timezone);
  v_end timestamptz := ((p_report_date + 1)::timestamp at time zone p_timezone);
  v_payload jsonb;
begin
  if p_page_key = 'gr_dashboard' then
    select jsonb_build_object(
      'guild', jsonb_build_object('id', g.id, 'name', g.name, 'memberCount', g.member_count, 'galacticPower', g.galactic_power, 'characterPower', g.character_power, 'shipPower', g.ship_power, 'lastSyncedAt', g.last_synced_at),
      'snapshot', coalesce((select to_jsonb(gs) - 'guild_id' from public.guild_snapshots gs where gs.guild_id=p_guild_id order by gs.captured_at desc limit 1),'{}'::jsonb),
      'membershipEvents', coalesce((select jsonb_object_agg(event_type,cnt) from (select event_type,count(*) cnt from public.guild_membership_history where guild_id=p_guild_id and occurred_at>=v_start and occurred_at<v_end group by event_type) x),'{}'::jsonb),
      'activity', jsonb_build_object(
        'inactive24h', (select count(*) from (select distinct on (player_id) player_id,last_activity_at from public.guild_member_activity_snapshots where guild_id=p_guild_id order by player_id,captured_at desc) a where a.last_activity_at < now()-interval '24 hours'),
        'inactive48h', (select count(*) from (select distinct on (player_id) player_id,last_activity_at from public.guild_member_activity_snapshots where guild_id=p_guild_id order by player_id,captured_at desc) a where a.last_activity_at < now()-interval '48 hours')
      )
    ) into v_payload from public.guilds g where g.id=p_guild_id;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key in ('member_data','tickets','ticket_dashboard') then
    select jsonb_build_object(
      'capturedFrom','latest-guild-member-activity',
      'members',coalesce(jsonb_agg(jsonb_build_object(
        'playerId',p.id,'allyCode',p.ally_code,'name',p.name,
        'galacticPower',gmc.member_galactic_power,'characterPower',gmc.member_character_power,'shipPower',gmc.member_ship_power,
        'guildJoinedAt',a.guild_joined_at,'lastActivityAt',a.last_activity_at,'memberLevel',a.member_level,'guildXp',a.guild_xp,
        'lifetimeSeasonScore',a.lifetime_season_score,'leagueId',a.league_id,'raidTicketsCurrent',a.raid_tickets_current,'raidTicketsLifetime',a.raid_tickets_lifetime,
        'memberContribution',coalesce(a.member_contribution,'[]'::jsonb),'seasonStatus',coalesce(a.season_status,'[]'::jsonb)
      ) order by p.name),'[]'::jsonb)
    ) into v_payload
    from public.guild_members_current gmc
    join public.players p on p.id=gmc.player_id
    left join lateral (
      select mas.* from public.guild_member_activity_snapshots mas
      where mas.guild_id=p_guild_id and mas.player_id=p.id
      order by mas.captured_at desc limit 1
    ) a on true
    where gmc.guild_id=p_guild_id;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'member_data_backup' then
    select jsonb_build_object('snapshotDate',p_report_date,'members',coalesce(jsonb_agg(to_jsonb(x) order by x.name),'[]'::jsonb)) into v_payload
    from (
      select p.ally_code,p.name,ps.galactic_power,ps.character_power,ps.ship_power,ps.character_count,ps.ship_count,ps.gl_count,ps.gear_13_count,ps.relic_5_plus_count,ps.relic_7_plus_count,ps.relic_9_count,ps.seven_star_ship_count,ps.zeta_count,ps.omicron_count,ps.ultimate_count,ps.omega_upgrade_count,ps.captured_at
      from public.player_snapshots ps join public.players p on p.id=ps.player_id
      where ps.guild_id=p_guild_id and ps.snapshot_date=p_report_date
    ) x;
    return coalesce(v_payload,jsonb_build_object('snapshotDate',p_report_date,'members','[]'::jsonb));
  elsif p_page_key = 'gl_report' then
    select jsonb_build_object('members',coalesce(jsonb_agg(member_row order by member_row->>'name'),'[]'::jsonb)) into v_payload
    from (
      select jsonb_build_object(
        'allyCode',p.ally_code,'name',p.name,
        'galacticLegends',coalesce((select jsonb_agg(jsonb_build_object('baseId',u.base_id,'name',gu.name,'rarity',u.rarity,'gearLevel',u.gear_level,'relicTier',u.relic_tier,'power',u.galactic_power,'ultimateUnlocked',u.ultimate_unlocked) order by gu.name)
          from public.player_units_current u join public.game_units gu on gu.base_id=u.base_id
          where u.player_id=p.id and 'galactic_legend'=any(gu.categories)),'[]'::jsonb)
      ) member_row
      from public.guild_members_current gmc join public.players p on p.id=gmc.player_id where gmc.guild_id=p_guild_id
    ) q;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'inquisitor_dashboard' then
    select jsonb_build_object('units',array['GRANDINQUISITOR','THIRDSISTER','FIFTHBROTHER','SEVENTHSISTER','EIGHTHBROTHER','NINTHSISTER','SECONDSISTER','MARROK'],
      'members',coalesce(jsonb_agg(member_row order by member_row->>'name'),'[]'::jsonb)) into v_payload
    from (
      select jsonb_build_object('allyCode',p.ally_code,'name',p.name,
        'inquisitors',coalesce((select jsonb_agg(jsonb_build_object('baseId',u.base_id,'name',gu.name,'rarity',u.rarity,'gearLevel',u.gear_level,'relicTier',u.relic_tier,'power',u.galactic_power) order by gu.name)
          from public.player_units_current u join public.game_units gu on gu.base_id=u.base_id
          where u.player_id=p.id and u.base_id=any(array['GRANDINQUISITOR','THIRDSISTER','FIFTHBROTHER','SEVENTHSISTER','EIGHTHBROTHER','NINTHSISTER','SECONDSISTER','MARROK'])),'[]'::jsonb)
      ) member_row
      from public.guild_members_current gmc join public.players p on p.id=gmc.player_id where gmc.guild_id=p_guild_id
    ) q;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'scorecards' then
    select jsonb_build_object('members',coalesce(jsonb_agg(jsonb_build_object(
      'allyCode',p.ally_code,'name',p.name,'galacticPower',gmc.member_galactic_power,'lastActivityAt',a.last_activity_at,'memberContribution',coalesce(a.member_contribution,'[]'::jsonb),
      'progressionEvents',(select count(*) from public.player_unit_progression_history ph where ph.guild_id=p_guild_id and ph.player_id=p.id and ph.changed_at>=v_start and ph.changed_at<v_end)
    ) order by p.name),'[]'::jsonb),'scope','partial-core-evidence') into v_payload
    from public.guild_members_current gmc join public.players p on p.id=gmc.player_id
    left join lateral (select mas.* from public.guild_member_activity_snapshots mas where mas.guild_id=p_guild_id and mas.player_id=p.id order by mas.captured_at desc limit 1) a on true
    where gmc.guild_id=p_guild_id;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'absences' then
    select jsonb_build_object('rows',coalesce(jsonb_agg(jsonb_build_object('id',a.id,'allyCode',p.ally_code,'name',p.name,'reason',a.reason,'startsAt',a.starts_at,'expectedReturnAt',a.expected_return_at,'actualReturnAt',a.actual_return_at,'status',a.status,'notes',a.notes) order by a.starts_at desc),'[]'::jsonb)) into v_payload
    from public.guild_member_absences a join public.players p on p.id=a.player_id where a.guild_id=p_guild_id;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'relationships' then
    select jsonb_build_object('rows',coalesce(jsonb_agg(jsonb_build_object('id',r.id,'allyCode',p.ally_code,'name',p.name,'relatedAllyCode',rp.ally_code,'relatedName',rp.name,'relationshipType',r.relationship_type,'label',r.label,'notes',r.notes) order by p.name,r.label),'[]'::jsonb)) into v_payload
    from public.guild_member_relationships r join public.players p on p.id=r.player_id left join public.players rp on rp.id=r.related_player_id where r.guild_id=p_guild_id;
    return coalesce(v_payload,'{}'::jsonb);
  elsif p_page_key = 'm_processing_cache' then
    return jsonb_build_object('guildId',p_guild_id,'reportDate',p_report_date,'latestGuildSnapshotId',(select id from public.guild_snapshots where guild_id=p_guild_id order by captured_at desc limit 1),'latestSyncRunId',(select id from public.guild_sync_runs where guild_id=p_guild_id and status='completed' order by completed_at desc limit 1));
  elsif p_page_key = 'about_guild_report' then
    return jsonb_build_object('sourceWorkbook','LV Unit Tracker (new)','migrationRule','Every workbook worksheet is registered in Guild Intelligence and receives a daily report-page record.');
  else
    select jsonb_build_object('workbookSheet',r.workbook_sheet,'title',r.title,'implementationStatus',r.implementation_status,'expectedSources',to_jsonb(r.expected_sources),'phase',r.phase,'description',r.description)
    into v_payload from public.guild_intelligence_page_registry r where r.page_key=p_page_key;
    return coalesce(v_payload,'{}'::jsonb);
  end if;
end
$$;

create or replace function public.capture_guild_intelligence_daily_report(
  p_guild_id uuid,
  p_report_date date,
  p_source_sync_job_id uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_settings public.guild_intelligence_settings%rowtype;
  v_report_id uuid;
  v_sync_run_id uuid;
  v_page record;
  v_captured int;
  v_partial int;
  v_pending int;
  v_na int;
  v_failed int;
  v_overall text;
begin
  select * into v_settings from public.guild_intelligence_settings where guild_id=p_guild_id;
  if not found then
    insert into public.guild_intelligence_settings(guild_id) values(p_guild_id) returning * into v_settings;
  end if;

  if p_source_sync_job_id is not null then
    select sync_run_id into v_sync_run_id from public.guild_sync_jobs where id=p_source_sync_job_id and guild_id=p_guild_id;
  end if;
  if v_sync_run_id is null then
    select id into v_sync_run_id from public.guild_sync_runs where guild_id=p_guild_id and status='completed' order by completed_at desc nulls last limit 1;
  end if;

  insert into public.guild_intelligence_daily_reports(guild_id,report_date,report_timezone,scheduled_local_time,status,source_sync_job_id,source_sync_run_id,captured_at,updated_at)
  values(p_guild_id,p_report_date,v_settings.report_timezone,v_settings.report_local_time,'capturing',p_source_sync_job_id,v_sync_run_id,now(),now())
  on conflict (guild_id,report_date) do update set report_timezone=excluded.report_timezone,scheduled_local_time=excluded.scheduled_local_time,status='capturing',source_sync_job_id=coalesce(excluded.source_sync_job_id,public.guild_intelligence_daily_reports.source_sync_job_id),source_sync_run_id=coalesce(excluded.source_sync_run_id,public.guild_intelligence_daily_reports.source_sync_run_id),captured_at=now(),error_message=null,updated_at=now()
  returning id into v_report_id;

  for v_page in select * from public.guild_intelligence_page_registry where daily_capture order by sort_order loop
    begin
      insert into public.guild_intelligence_daily_pages(report_id,guild_id,report_date,page_key,capture_status,captured_at,source_sync_run_id,payload,metrics,error_message)
      values(v_report_id,p_guild_id,p_report_date,v_page.page_key,public.guild_intelligence_capture_status(v_page.implementation_status),now(),v_sync_run_id,public.guild_intelligence_page_payload(p_guild_id,v_page.page_key,p_report_date,v_settings.report_timezone),jsonb_build_object('implementationStatus',v_page.implementation_status,'phase',v_page.phase),null)
      on conflict (report_id,page_key) do update set capture_status=excluded.capture_status,captured_at=excluded.captured_at,source_sync_run_id=excluded.source_sync_run_id,payload=excluded.payload,metrics=excluded.metrics,error_message=null;
    exception when others then
      insert into public.guild_intelligence_daily_pages(report_id,guild_id,report_date,page_key,capture_status,captured_at,source_sync_run_id,payload,metrics,error_message)
      values(v_report_id,p_guild_id,p_report_date,v_page.page_key,'failed',now(),v_sync_run_id,'{}'::jsonb,jsonb_build_object('implementationStatus',v_page.implementation_status,'phase',v_page.phase),left(sqlerrm,1000))
      on conflict (report_id,page_key) do update set capture_status='failed',captured_at=excluded.captured_at,error_message=excluded.error_message;
    end;
  end loop;

  select count(*) filter(where capture_status='captured'),count(*) filter(where capture_status='partial'),count(*) filter(where capture_status='source_pending'),count(*) filter(where capture_status='not_applicable'),count(*) filter(where capture_status='failed')
  into v_captured,v_partial,v_pending,v_na,v_failed from public.guild_intelligence_daily_pages where report_id=v_report_id;
  v_overall := case when v_failed>0 then 'failed' when v_partial>0 or v_pending>0 then 'partial' else 'completed' end;

  update public.guild_intelligence_daily_reports set status=v_overall,completed_at=now(),summary=jsonb_build_object('totalPages',v_captured+v_partial+v_pending+v_na+v_failed,'captured',v_captured,'partial',v_partial,'sourcePending',v_pending,'notApplicable',v_na,'failed',v_failed,'returnedEvents',(select count(*) from public.guild_membership_history where guild_id=p_guild_id and event_type='returned' and occurred_at>=p_report_date::timestamp at time zone v_settings.report_timezone and occurred_at<(p_report_date+1)::timestamp at time zone v_settings.report_timezone)),updated_at=now() where id=v_report_id;

  update public.guild_intelligence_settings set last_completed_report_date=p_report_date,last_completed_at=now(),last_error=case when v_failed>0 then 'One or more Guild Intelligence pages failed capture.' else null end,updated_at=now() where guild_id=p_guild_id;
  return v_report_id;
end
$$;

create or replace function public.read_guild_intelligence_status(p_ally_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_code text := regexp_replace(coalesce(p_ally_code,''),'[^0-9]','','g');
  v_guild_id uuid;
  v_report_id uuid;
  v_result jsonb;
begin
  if length(v_code)<>9 then return null; end if;
  select p.current_guild_id into v_guild_id from public.players p where p.ally_code=v_code limit 1;
  if v_guild_id is null then return null; end if;
  select id into v_report_id from public.guild_intelligence_daily_reports where guild_id=v_guild_id order by report_date desc,captured_at desc nulls last limit 1;
  select jsonb_build_object(
    'guild',jsonb_build_object('id',g.id,'name',g.name,'memberCount',g.member_count,'galacticPower',g.galactic_power,'lastSyncedAt',g.last_synced_at),
    'settings',coalesce((select to_jsonb(s)-'guild_id' from public.guild_intelligence_settings s where s.guild_id=v_guild_id),'{}'::jsonb),
    'latestReport',coalesce((select to_jsonb(r)-'guild_id' from public.guild_intelligence_daily_reports r where r.id=v_report_id),'null'::jsonb),
    'returnedTotal',(select count(*) from public.guild_membership_history mh where mh.guild_id=v_guild_id and mh.event_type='returned'),
    'pages',coalesce((select jsonb_agg(jsonb_build_object('pageKey',reg.page_key,'workbookSheet',reg.workbook_sheet,'title',reg.title,'category',reg.category,'sourceKind',reg.source_kind,'implementationStatus',reg.implementation_status,'phase',reg.phase,'dailyCapture',reg.daily_capture,'userFacing',reg.user_facing,'sortOrder',reg.sort_order,'description',reg.description,'expectedSources',to_jsonb(reg.expected_sources),'captureStatus',dp.capture_status,'capturedAt',dp.captured_at,'metrics',coalesce(dp.metrics,'{}'::jsonb),'error',dp.error_message) order by reg.sort_order) from public.guild_intelligence_page_registry reg left join public.guild_intelligence_daily_pages dp on dp.report_id=v_report_id and dp.page_key=reg.page_key),'[]'::jsonb)
  ) into v_result from public.guilds g where g.id=v_guild_id;
  return v_result;
end
$$;

