create table if not exists public.guild_intelligence_daily_reports (
  id uuid primary key default gen_random_uuid(),
  guild_id uuid not null references public.guilds(id) on delete cascade,
  report_date date not null,
  report_timezone text not null,
  scheduled_local_time time not null default '00:00:00',
  status text not null default 'queued' check (status in ('queued','capturing','completed','partial','failed')),
  source_sync_job_id uuid references public.guild_sync_jobs(id) on delete set null,
  source_sync_run_id uuid references public.guild_sync_runs(id) on delete set null,
  captured_at timestamptz,
  completed_at timestamptz,
  summary jsonb not null default '{}'::jsonb,
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (guild_id, report_date)
);

create table if not exists public.guild_intelligence_daily_pages (
  id bigint generated by default as identity primary key,
  report_id uuid not null references public.guild_intelligence_daily_reports(id) on delete cascade,
  guild_id uuid not null references public.guilds(id) on delete cascade,
  report_date date not null,
  page_key text not null references public.guild_intelligence_page_registry(page_key) on delete restrict,
  capture_status text not null check (capture_status in ('captured','partial','source_pending','not_applicable','failed')),
  captured_at timestamptz not null default now(),
  source_sync_run_id uuid references public.guild_sync_runs(id) on delete set null,
  payload jsonb not null default '{}'::jsonb,
  metrics jsonb not null default '{}'::jsonb,
  error_message text,
  unique (report_id, page_key)
);

