  page_key text primary key,
  workbook_sheet text not null unique,
  title text not null,
  category text not null,
  source_kind text not null,
  implementation_status text not null check (implementation_status in ('active','partial','pending_source','legacy_reference')),
  phase smallint not null default 1 check (phase between 1 and 9),
  daily_capture boolean not null default true,
  user_facing boolean not null default true,
  sort_order smallint not null,
  description text not null default '',
  expected_sources text[] not null default '{}'::text[],
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
