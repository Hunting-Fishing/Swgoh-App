  guild_id uuid primary key references public.guilds(id) on delete cascade,
  enabled boolean not null default true,
  report_timezone text not null default 'America/Phoenix',
  report_local_time time not null default '00:00:00',
  last_enqueued_report_date date,
  last_enqueued_at timestamptz,
  last_completed_report_date date,
  last_completed_at timestamptz,
  last_error text,
