const ALIASES = Object.freeze({
  'en-us': 'en', 'en-gb': 'en',
  'es-es': 'es', 'es-419': 'es', 'es-mx': 'es',
  'fr-fr': 'fr', 'fr-ca': 'fr',
  'de-de': 'de',
  'fil-ph': 'fil', 'tl': 'fil', 'tl-ph': 'fil',
});

export const DISCORD_SUPPORTED_LOCALES = Object.freeze(Object.keys(CATALOG));

export function normalizeDiscordLocale(value, fallback = 'en') {
  const raw = String(value ?? '').trim().replace('_', '-').toLowerCase();
  if (!raw) return DISCORD_SUPPORTED_LOCALES.includes(fallback) ? fallback : 'en';
  if (CATALOG[raw]) return raw;
  if (ALIASES[raw]) return ALIASES[raw];
  const primary = raw.split('-')[0];
  if (CATALOG[primary]) return primary;
  return DISCORD_SUPPORTED_LOCALES.includes(fallback) ? fallback : 'en';
}

export function discordLocaleChoices() {
  return DISCORD_SUPPORTED_LOCALES.map((locale) => Object.freeze({ locale, name: CATALOG[locale].languageName }));
}

function interpolate(template, params = {}) {
  return String(template ?? '').replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, key) => String(params[key] ?? ''));
}

export function t(localeInput, key, params = {}) {
  const locale = normalizeDiscordLocale(localeInput);
  const template = CATALOG[locale]?.[key] ?? CATALOG.en[key] ?? key;
  return interpolate(template, params);
}

export function languageName(localeInput) {
  const locale = normalizeDiscordLocale(localeInput);
  return CATALOG[locale]?.languageName || CATALOG.en.languageName;
}

export function formatLocaleNumber(localeInput, value) {
  const locale = normalizeDiscordLocale(localeInput);
  try { return new Intl.NumberFormat(locale).format(Number(value || 0)); }
  catch { return new Intl.NumberFormat('en').format(Number(value || 0)); }
}
